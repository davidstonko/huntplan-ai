/**
 * Helper for the Fish map UI — returns hotspots filtered by water class.
 * Cheap O(n) walk; the dataset is small enough that memoization is overkill.
 */
export function hotspotsByWaterClass(cls: HotspotWaterClass): FishingHotspot[] {
  return MARYLAND_FISHING_HOTSPOTS.filter((h) => h.waterClass === cls);
}

/**
 * Helper for the AI chat — returns hotspots that match the given month
 * abbreviation (e.g. "Apr"). Used by fishingChatKnowledge to answer
 * "where should I fish this month" questions.
 */
export function hotspotsForMonth(monthAbbr: string): FishingHotspot[] {
  const target = monthAbbr.slice(0, 3).toLowerCase();
  return MARYLAND_FISHING_HOTSPOTS.filter((h) =>
    h.bestMonths
      .toLowerCase()
      .split(',')
      .map((m) => m.trim())
      .includes(target),
  );
}

