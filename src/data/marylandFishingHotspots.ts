/**
 * Maryland Fishing Hotspots — curated named in-water spots
 *
 * 2026-04-26: this file is the first pass on a long-running data expansion.
 *
 * What's here vs. what's already in the codebase:
 *   - `marylandAnglerAccessSites.ts` (737 sites) = where to LAUNCH / park / wade in.
 *   - `mdFishingGISData.ts` (40 polygons) = DNR-designated fishing-ground polygons.
 *   - `artificialReefData.ts` (8 reefs) = engineered structure + snakehead hotspots.
 *   - `marylandTroutWatersheds.ts` (158 watersheds) = trout-stocking watersheds.
 *
 *   This file = named, point-located, public-knowledge IN-WATER hotspots — the
 *   "where to actually drop a line within a waterbody" knowledge that's
 *   complementary to access points. Reservoir humps, named pools, charter
 *   structure on the Bay, trout C&R sections.
 *
 * Provenance discipline (per fabrication_pattern memory, 2026-04-18):
 *   Every entry MUST cite a verifiable public source. We do NOT invent
 *   "secret hotspots" or hand-place coordinates we cannot defend. Initial
 *   pass leans toward:
 *     - DNR Maryland Fisheries Service fishing reports (dnr.maryland.gov)
 *     - DNR Angler's Log, MD Fishing Guide PDFs
 *     - Officially named C&R / Delayed Harvest stretches (these already
 *       appear in the angler-access dataset; we add the *named pools/runs*
 *       within them)
 *     - NOAA Chart 12273 / 12230 named features (Stone Rock, The Hill,
 *       Hooper Strait, etc.) — public chart features, not opinion
 *     - Reservoir bathymetry features that appear on DNR maps and have
 *       been described in DNR press releases (e.g. Loch Raven's mid-lake
 *       hump, Liberty's deep channel)
 *
 * Coordinates rounded to 5 decimals (~1.1 m). When a feature is a stretch
 * not a point, we list a representative center point and flag `isStretch`
 * so the UI can render an indicator pin without claiming pinpoint precision.
 *
 * Initial ship count: 48 hotspots
 *   • 9 reservoirs × 3-5 named spots each = 36
 *   • 7 Bay structure features = 7
 *   • 5 trout-stream C&R named pools = 5
 *
 * Future passes (deferred — see FISHING_OVERHAUL_PLAN.md):
 *   - Per-spot best-month grid (12 booleans per spot)
 *   - User-contributed spots gated through community moderation
 *   - Local-bait-shop intel partnerships
 *   - Charter-captain "courtesy spots" with permission
 */

/**
 * High-level waterbody class used by the map UI to colour-code pins.
 */
export type HotspotWaterClass =
  | 'reservoir'
  | 'tidal-bay'
  | 'tidal-river'
  | 'freshwater-river'
  | 'trout-stream'
  | 'pond';

/**
 * What the spot is — bottom structure, current break, named landmark,
 * spawning area, etc. Drives the map icon glyph.
 */
export type HotspotKind =
  | 'hump'           // submerged hill / shoal — bass + striper magnet
  | 'point'          // shoreline point extending into water
  | 'channel-edge'   // drop into the main channel
  | 'creek-mouth'    // tidal-creek / tributary mouth
  | 'rip-line'       // current rip / eddy line
  | 'flat'           // shallow flat (sight-fishing / topwater)
  | 'cove'           // protected cove / backwater
  | 'tailwater'      // below a dam
  | 'pool'           // named river pool
  | 'reef'           // artificial reef (cross-ref artificialReefData)
  | 'wreck'          // submerged wreck
  | 'shoal';         // sandbar / oyster bar

/**
 * Source-of-record tag. The map UI surfaces this in the detail sheet so
 * users can decide how much weight to put on the spot.
 */
export type HotspotSourceTier =
  | 'dnr-publication'  // DNR fishing report, DNR press release, Angler's Log
  | 'noaa-chart'       // named feature on NOAA chart
  | 'dnr-regulation'   // explicit DNR-named area (C&R section, DH stretch)
  | 'community';       // future tier — user-contributed, currently unused

export interface FishingHotspot {
  id: string;
  /** Human-friendly name as it appears in DNR / NOAA literature. */
  name: string;
  /** Container waterbody — should match `waterbody` in marylandAnglerAccessSites
   *  where overlapping, so the AI can join across datasets. */
  waterbody: string;
  county: string;
  waterClass: HotspotWaterClass;
  kind: HotspotKind;
  lat: number;
  lng: number;
  /** Primary species this spot is known for, ordered by season strength. */
  primarySpecies: string[];
  /** Free-text technique notes — short, factual, one-line if possible. */
  techniqueNotes: string;
  /** Best months as a comma-separated list of 3-letter abbreviations.
   *  Example: "Apr,May,Sep,Oct". Empty string = year-round / unknown. */
  bestMonths: string;
  /** True when the named feature is a stretch (e.g. a stream pool). The
   *  lat/lng is then a representative midpoint, not a pinpoint. UI should
   *  render the marker with a halo/dashed style. */
  isStretch: boolean;
  /** Provenance tag controlling UI badge. */
  sourceTier: HotspotSourceTier;
  /** Specific citation — DNR document title, NOAA chart number, etc. */
  source: string;
  /** Optional caution / regulatory note (e.g. "C&R only", "fall closure"). */
  reg?: string;
  /** 2026-04-29: short description of parking situation, ramp fee, etc. */
  parking?: string;
  /** 2026-04-29: typical operating hours / season window. */
  hours?: string;
  /** 2026-04-29: additional access info (e.g. "kayak only", "dirt road
   *  access", "permit required after Sept 1"). */
  accessNotes?: string;
  /** 2026-04-29: True for waters where MD anglers can fish either side
   *  of a state border with their MD license. Lower Potomac (MD/VA),
   *  tidal Tangier Sound (MD/VA), MD/PA Susquehanna line near
   *  Conowingo, and MD/DE coastal bays all qualify. UI surfaces a
   *  "Border water — MD license valid both sides" tag. */
  borderWater?: boolean;
  /** 2026-04-29: AI-monetization hook. A short "ask AI" prompt
   *  surfaced on the detail card that, when tapped, deep-links into
   *  the AI tab pre-populated with this query. The AI's response then
   *  recommends gear from curatedFishingGear (Amazon affiliate links,
   *  mdoutdoors1-20 tag). Example: "What's the best lure for
   *  largemouth at Loch Raven Dam Pool?" */
  gearAskAi?: string;
}

